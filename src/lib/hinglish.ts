export function phoneticWordToDevanagari(word: string): string {
  let s = word.toLowerCase();
  let result = "";
  let i = 0;
  let lastWasConsonant = false;

  while (i < s.length) {
    let matched = false;

    if (!lastWasConsonant) {
      // Try initial vowels first
      for (const [rom, dev] of PHONETIC_VOWELS_INITIAL) {
        if (s.startsWith(rom, i)) {
          result += dev;
          i += rom.length;
          matched = true;
          lastWasConsonant = false;
          break;
        }
      }
      if (matched) continue;
    } else {
      // Try matras
      for (const [rom, matra] of PHONETIC_VOWELS_MATRA) {
        if (s.startsWith(rom, i)) {
          result += matra;
          i += rom.length;
          matched = true;
          lastWasConsonant = false;
          break;
        }
      }
      if (matched) continue;
    }

    // Try consonants
    for (const [rom, dev] of PHONETIC_CONSONANTS) {
      if (s.startsWith(rom, i)) {
        result += dev;
        i += rom.length;
        matched = true;
        lastWasConsonant = true;
        break;
      }
    }
    if (matched) continue;

    // Single unhandled character fallback
    result += s[i];
    i++;
    lastWasConsonant = false;
  }

  return result;
}

export function toEnglishGloss(text: string): string {
  const tokens = text.split(/\s+/);
  const out: string[] = [];
  for (const tok of tokens) {
    const m = tok.match(/^([A-Za-z]+)([.,!?;:]*)$/);
    if (m) {
      const core = m[1]!;
      const punct = m[2] ?? "";
      const low = core.toLowerCase();
      if (low in HINGLISH_TO_EN) {
        const eng = HINGLISH_TO_EN[low]!;
        if (eng === "") continue;
        const final =
          core[0] === core[0]?.toUpperCase() ? eng.charAt(0).toUpperCase() + eng.slice(1) : eng;
        out.push(final + punct);
      } else out.push(tok);
    } else {
      const low = tok.toLowerCase().replace(/[,.!?;:"'()[\]{}]/g, "");
      if (low in HINGLISH_TO_EN && HINGLISH_TO_EN[low] === "") continue;
      if (low in HINGLISH_TO_EN) out.push(HINGLISH_TO_EN[low]!);
      else out.push(tok);
    }
  }
  const j = out.join(" ").replace(/\s+/g, " ").trim();
  return j || text;
}

export function toDevanagariApprox(text: string): string {
  const tokens = text.split(/(\s+)/);
  return tokens
    .map((tok) => {
      if (/^\s+$/.test(tok)) return tok;
      const m = tok.match(/^([A-Za-z]+)([.,!?;:]*)$/);
      if (!m) return tok;
      const core = m[1]!;
      const punct = m[2] ?? "";
      const dev = phoneticWordToDevanagari(core);
      return dev + punct;
    })
    .join("");
}

export function codeMixRatio(text: string): number {
  const dev = (text.match(/[\u0900-\u097F]/g) || []).length
    ? text.split(/\s+/).filter((t) => /[\u0900-\u097F]/.test(t)).length
    : 0;
  const toks = text.split(/\s+/);
  const n = toks.length || 1;
  const roman = toks.filter((t) => {
    const low = t.toLowerCase().replace(/[,.!?;:"'()[\]{}]/g, "");
    return (
      low in HINGLISH_TO_EN ||
      ["ka", "ki", "ke", "ko", "mein", "me", "par", "se", "tak", "liye", "bhi", "hi"].includes(low)
    );
  }).length;
  return Math.min(1, (dev + roman) / n);
}

